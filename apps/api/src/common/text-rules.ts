// Общие правила пользовательского текста: имя пользователя (`users/user-name.ts`), название встречи
// и имена участников (`meetings/dto.ts`). Нейтральный модуль, чтобы `users` и `meetings` не зависели
// друг от друга.

// Запрещённые символы: управляющие (в том числе нулевой байт, который Postgres не принимает в text)
// и bidi-управляющие (U+202E и др. меняют порядок отображения: `abc‮gnp.exe`).
// ZWJ не запрещаем: он нужен составным эмодзи и некоторым письменностям.
// Тот же набор — в `validateName` на вебе (`apps/web/src/lib/profile-name.ts`).
export const NAME_ALLOWED_PATTERN = '^[^\\p{Cc}\\p{Bidi_Control}]*$'

// Тот же набор для `pattern` в Swagger: в OpenAPI у регулярки нет флага `u`, и клиенты
// (Ajv по умолчанию, генераторы) прочли бы `\p{Cc}` как буквы `p`, `{`, `C`… Поэтому диапазоны
// перечислены явно; совпадение с NAME_ALLOWED_PATTERN проверяет `text-rules.spec.ts`
export const NAME_ALLOWED_SCHEMA_PATTERN =
  '^[^\\u0000-\\u001F\\u007F-\\u009F\\u061C\\u200E\\u200F\\u202A-\\u202E\\u2066-\\u2069]*$'

// Хотя бы один видимый символ. Пустыми выглядят и потому не считаются: пробелы (`\s`, `\p{Z}`),
// невидимые символы формата (`\p{Cf}`: zero-width space, soft hyphen), одиночные комбинирующие
// знаки (`\p{M}`) и filler-символы, которые рисуются пустым местом (U+115F, U+1160, U+3164, U+FFA0 —
// хангыль, U+2800 — пустой символ Брайля)
export const VISIBLE_TEXT = /[^\s\p{Z}\p{Cf}\p{M}ᅟᅠ⠀ㅤﾠ]/u
